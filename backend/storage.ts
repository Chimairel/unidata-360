import { AsyncLocalStorage } from "node:async_hooks";
import { Pool, type PoolClient } from "pg";

type Value = string | number | null;
type Connection = {
  transaction: boolean;
  rows<T>(sql: string, args: Value[]): Promise<T[]>;
  exec(sql: string): Promise<void>;
};
const context = new AsyncLocalStorage<Connection>();
let pool: Pool | undefined;
let initialization: Promise<void> | undefined;
const lock = "SELECT pg_advisory_xact_lock(1947183060)";

function postgresConnection(client: PoolClient): Connection {
  return {
    transaction: false,
    async rows<T>(sql: string, args: Value[]) {
      let index = 0;
      return (
        await client.query(
          sql.replace(/\?/g, () => `$${++index}`),
          args,
        )
      ).rows as T[];
    },
    async exec(sql) {
      await client.query(sql);
    },
  };
}

async function connect<T>(
  fn: (connection: Connection) => Promise<T>,
): Promise<T> {
  const url = process.env.DATABASE_URL;
  if (!url) {
    throw new Error("Set DATABASE_URL to a PostgreSQL connection string.");
  }
  if (!pool) {
    const connectionString = URL.parse(url);
    if (
      !connectionString ||
      !["postgres:", "postgresql:"].includes(connectionString.protocol) ||
      !connectionString.hostname
    ) {
      throw new Error("DATABASE_URL must be a PostgreSQL connection string.");
    }
    const local =
      !process.env.VERCEL &&
      !process.env.RAILWAY_PROJECT_ID &&
      ["localhost", "127.0.0.1", "[::1]"].includes(connectionString.hostname) &&
      connectionString.searchParams.get("sslmode") === "disable";
    // Cloud connections always verify the database server's TLS certificate.
    for (const key of ["sslmode", "sslcert", "sslkey", "sslrootcert", "ssl"])
      connectionString.searchParams.delete(key);
    pool = new Pool({
      connectionString: connectionString.href,
      ssl: local ? false : { rejectUnauthorized: true },
      max: 6,
      connectionTimeoutMillis: 12000,
    });
    pool.on("error", () =>
      console.error("An idle PostgreSQL connection was closed."),
    );
  }
  const client = await pool.connect();
  try {
    return await fn(postgresConnection(client));
  } finally {
    client.release();
  }
}

async function inTransaction<T>(
  db: Connection,
  fn: () => Promise<T>,
  write: boolean,
) {
  if (db.transaction) return fn();
  await db.exec(
    write ? "BEGIN" : "BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY",
  );
  try {
    // A shared write lock preserves the linear audit chain and serializes ETL/import.
    if (write) await db.exec(lock);
    const result = await context.run({ ...db, transaction: true }, fn);
    await db.exec("COMMIT");
    return result;
  } catch (error) {
    await db.exec("ROLLBACK").catch(() => {});
    throw error;
  }
}

async function schema(db: Connection) {
  const sequence = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
  await db.exec(`
    CREATE TABLE IF NOT EXISTS sources (feed TEXT NOT NULL, record_key TEXT NOT NULL, payload TEXT NOT NULL, PRIMARY KEY(feed,record_key));
    CREATE TABLE IF NOT EXISTS master (id TEXT PRIMARY KEY, payload TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS etl_runs (seq ${sequence}, payload TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS audit (seq ${sequence}, payload TEXT NOT NULL, previous_hash TEXT NOT NULL, hash TEXT NOT NULL);
    CREATE TABLE IF NOT EXISTS sessions (id TEXT PRIMARY KEY, role TEXT NOT NULL, expires_at BIGINT NOT NULL, user_id TEXT);
    CREATE TABLE IF NOT EXISTS users (id TEXT PRIMARY KEY, email TEXT UNIQUE NOT NULL, display_name TEXT NOT NULL, password_hash TEXT NOT NULL, role TEXT NOT NULL, student_id TEXT, active INTEGER NOT NULL DEFAULT 1);
    CREATE TABLE IF NOT EXISTS login_attempts (email TEXT PRIMARY KEY, failures INTEGER NOT NULL, retry_at BIGINT NOT NULL);
    CREATE TABLE IF NOT EXISTS student_registrations (token_hash TEXT PRIMARY KEY, email TEXT NOT NULL, student_id TEXT NOT NULL, expires_at BIGINT NOT NULL, delivered INTEGER NOT NULL DEFAULT 0);
    CREATE TABLE IF NOT EXISTS registration_limits (key TEXT PRIMARY KEY, attempts INTEGER NOT NULL, window_end BIGINT NOT NULL, last_attempt BIGINT NOT NULL);
    CREATE TABLE IF NOT EXISTS interventions (student_id TEXT PRIMARY KEY, payload TEXT NOT NULL);
    ALTER TABLE users ADD COLUMN IF NOT EXISTS department TEXT;
    CREATE UNIQUE INDEX IF NOT EXISTS student_account_id_unique ON users(lower(student_id)) WHERE role='STUDENT' AND student_id IS NOT NULL;
    CREATE TABLE IF NOT EXISTS password_resets (token_hash TEXT PRIMARY KEY, user_id TEXT NOT NULL, email TEXT NOT NULL, expires_at BIGINT NOT NULL, delivered INTEGER NOT NULL DEFAULT 0);
    ALTER TABLE password_resets ADD COLUMN IF NOT EXISTS email TEXT;
    UPDATE users SET role='REGISTRAR' WHERE role='DEAN_REGISTRAR';
    UPDATE sessions SET role='REGISTRAR' WHERE role='DEAN_REGISTRAR';
    CREATE OR REPLACE FUNCTION reject_unidata_audit_change() RETURNS trigger LANGUAGE plpgsql AS $$
      BEGIN RAISE EXCEPTION 'Audit records are append-only'; END;
    $$;
    CREATE OR REPLACE TRIGGER audit_append_only BEFORE UPDATE OR DELETE OR TRUNCATE ON audit
    FOR EACH STATEMENT EXECUTE FUNCTION reject_unidata_audit_change();
  `);
}

export async function withStorage<T>(
  seed: () => Promise<void>,
  fn: (db: Connection) => Promise<T>,
  transaction?: "read" | "write",
): Promise<T> {
  const current = context.getStore();
  if (current)
    return transaction
      ? inTransaction(current, () => fn(current), transaction === "write")
      : fn(current);
  initialization ??= connect((db) =>
    inTransaction(
      db,
      async () => {
        await schema(db);
        if (!(await db.rows("SELECT 1 FROM etl_runs LIMIT 1", [])).length)
          await seed();
      },
      true,
    ),
  ).catch((error) => {
    initialization = undefined;
    throw error;
  });
  await initialization;
  return connect((db) =>
    context.run(db, () =>
      transaction
        ? inTransaction(db, () => fn(db), transaction === "write")
        : fn(db),
    ),
  );
}

export async function closeStorage() {
  await pool?.end();
  pool = undefined;
  initialization = undefined;
}
